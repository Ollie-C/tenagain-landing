import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, renameSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { beginBuild, finishBuild, verifyBuildProvenance } from './build-provenance.mjs';
import { receipt } from './pages-staging.mjs';

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
async function fixture(run) {
  const previous = process.cwd();
  const temp = mkdtempSync(join(tmpdir(), 'landing-provenance-test-'));
  try {
    const repo = join(temp, 'repo');
    mkdirSync(repo);
    process.chdir(repo);
    git('init', '-q', '-b', 'main');
    for (const path of ['src', 'functions', 'dist/api', '.astro']) mkdirSync(path, { recursive: true });
    writeFileSync('.gitignore', 'node_modules\n');
    writeFileSync('src/input.js', 'export const input = 1;\n');
    writeFileSync('functions/_middleware.ts', 'export {};\n');
    writeFileSync('dist/api/release', JSON.stringify({ status: 'ok', release: 'old' }));
    writeFileSync('.astro/cache', 'old cache');
    git('add', '.');
    git('-c', 'user.name=Local fixture', '-c', 'user.email=fixture@example.invalid',
      '-c', 'core.hooksPath=/dev/null', 'commit', '-qm', 'Synthetic source');
    const env = { DEPLOY_SHA: git('rev-parse', 'HEAD'), PAGES_BUILD_PROVENANCE: join(temp, 'proof.json') };
    const build = () => {
      writeFileSync('dist/api/release', JSON.stringify({ status: 'ok', release: env.DEPLOY_SHA }));
      writeFileSync('dist/new.js', 'generated bytes');
      writeFileSync('.astro/cache', 'updated cache');
    };
    await run({ env, build });
  } finally {
    process.chdir(previous);
    rmSync(temp, { recursive: true, force: true });
  }
}

test('clean exact source plus generated-only output yields a stable artifact hash and truthful dirty flag', () => fixture(async ({ env, build }) => {
  await beginBuild(env);
  build();
  const proof = await finishBuild(env);
  assert.equal(proof.expected_commit_dirty, true);
  assert.equal(proof.artifact_files, 2);
  assert.deepEqual(proof.generated_paths, ['.astro/cache', 'dist/api/release', 'dist/new.js']);
  assert.match(proof.artifact_sha256, /^[a-f0-9]{64}$/);
  mkdirSync('.wrangler');
  writeFileSync('.wrangler/cache', 'upload tool output');
  assert.deepEqual(await verifyBuildProvenance(env), proof);
  writeFileSync('dist/new.js', 'changed after capture');
  await assert.rejects(verifyBuildProvenance(env), /output changed/);
}));

test('build cannot start with dirty tracked source, untracked input, wrong SHA or an inside-checkout proof', () => fixture(async ({ env }) => {
  writeFileSync('src/input.js', 'modified');
  await assert.rejects(beginBuild(env), /clean checkout/);
  git('restore', 'src/input.js');
  writeFileSync('functions/new.ts', 'new input');
  await assert.rejects(beginBuild(env), /clean checkout/);
  rmSync('functions/new.ts');
  await assert.rejects(beginBuild({ ...env, DEPLOY_SHA: 'a'.repeat(40) }), /differs from tested SHA/);
  await assert.rejects(beginBuild({ ...env, PAGES_BUILD_PROVENANCE: join(process.cwd(), 'proof.json') }), /outside checkout/);
}));

test('source edits, new source and moves into generated directories fail after-build validation', async () => {
  for (const mutate of [
    () => writeFileSync('src/input.js', 'changed during build'),
    () => writeFileSync('functions/new.ts', 'unexpected input'),
    () => renameSync('src/input.js', 'dist/renamed.js'),
    () => { mkdirSync(' dist'); writeFileSync(' dist/new.js', 'not the allowed directory'); },
  ]) await fixture(async ({ env, build }) => {
    await beginBuild(env);
    build();
    mutate();
    await assert.rejects(finishBuild(env), /outside generated directories/);
  });
});

test('missing/stale/incomplete proof and repeated phase calls fail closed', () => fixture(async ({ env, build }) => {
  await assert.rejects(verifyBuildProvenance(env));
  await beginBuild(env);
  await assert.rejects(beginBuild(env));
  await assert.rejects(verifyBuildProvenance(env), /Incomplete/);
  build();
  await finishBuild(env);
  await assert.rejects(finishBuild(env), /already completed/);
  const proof = JSON.parse(readFileSync(env.PAGES_BUILD_PROVENANCE, 'utf8'));
  proof.source_tree = 'f'.repeat(40);
  writeFileSync(env.PAGES_BUILD_PROVENANCE, JSON.stringify(proof));
  await assert.rejects(verifyBuildProvenance(env), /identity mismatch/);
}));

test('wrong built release and symlinked deployment bytes cannot acquire provenance', async () => {
  await fixture(async ({ env, build }) => {
    await beginBuild(env);
    build();
    writeFileSync('dist/api/release', JSON.stringify({ status: 'ok', release: 'a'.repeat(40) }));
    await assert.rejects(finishBuild(env), /release differs/);
  });
  await fixture(async ({ env, build }) => {
    await beginBuild(env);
    build();
    symlinkSync('../src/input.js', 'dist/link.js');
    await assert.rejects(finishBuild(env), /symlinks/);
  });
});

test('tracked or untracked source changes after capture invalidate the receipt proof', async () => {
  for (const path of ['src/input.js', 'functions/new.ts']) await fixture(async ({ env, build }) => {
    await beginBuild(env);
    build();
    await finishBuild(env);
    writeFileSync(path, 'late source input');
    await assert.rejects(verifyBuildProvenance(env), /Source changed/);
  });
});

test('real Git/build proof qualifies matching dirty provider metadata without falsifying the flag', () => fixture(async ({ env, build }) => {
  await beginBuild(env);
  build();
  const proof = await finishBuild(env);
  const settings = { ...env, CLOUDFLARE_API_TOKEN: 'synthetic-only',
    CLOUDFLARE_ACCOUNT_ID: 'a'.repeat(32), CLOUDFLARE_PAGES_PROJECT: 'tenagain-landing',
    STAGING_PAGES_PROJECT_ID: 'b'.repeat(32), PAGES_DEPLOYMENT_ID: 'd'.repeat(32),
    PAGES_DEPLOYMENT_URL: 'https://1234abcd.tenagain-landing.pages.dev' };
  const project = { id: settings.STAGING_PAGES_PROJECT_ID, name: 'tenagain-landing',
    subdomain: 'tenagain-landing.pages.dev', production_branch: 'main', source: null };
  const deployed = { id: settings.PAGES_DEPLOYMENT_ID, project_id: project.id,
    project_name: project.name, short_id: '1234abcd', url: settings.PAGES_DEPLOYMENT_URL,
    environment: 'preview', is_skipped: false, latest_stage: { name: 'deploy', status: 'success' },
    deployment_trigger: { metadata: { branch: 'staging', commit_hash: env.DEPLOY_SHA, commit_dirty: true } } };
  const fetcher = async url => ({ ok: true, json: async () => ({ success: true,
    result: url.endsWith('/tenagain-landing') ? project : deployed }) });
  const verified = await receipt(settings, fetcher);
  assert.equal(verified.provider_commit_dirty, true);
  assert.equal(verified.artifact_sha256, proof.artifact_sha256);
  assert.equal(verified.release_sha, env.DEPLOY_SHA);
  writeFileSync('dist/new.js', 'late artifact mutation');
  await assert.rejects(receipt(settings, fetcher), /output changed/);
}));
